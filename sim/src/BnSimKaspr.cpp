BnSimKaspr::BnSimKaspr(const Options &opt)
    : Manager("bnsim_manager"), opt_(opt),
      venue_(opt.futures ? en::x::BINANCEF : en::x::BINANCE)
{
  logger_ = new polonaise::logger::act::Logger("bnsim_log", nullptr);
  add_to_manage_q(logger_);
  group_ = new actors::Group("bnsim_group");

  load_config();
  create_order_book();
  timer_ = new frame::mtim::act::Timer(ob_);   // advanced by the book's end-of-burst
  group_->add(timer_);
  logger_->set_timer(timer_);
  create_probe();
  create_som();
  create_lights();
  if (probe_)
  {
    probe_->set_lights(buy_lights_, sel_lights_);
    probe_->set_coords(pcoord_buy_, pcoord_sel_);
  }
  auto pm = create_PositionManager("bnsim", pcoord_map_);
  group_->add(pm);
  add_to_manage_q(group_);
  create_feed();   // its own thread, outside the group
}

/**
 * binance.ini holds one section per symbol:
 *
 *   BTCUSDT { tick 0.01  chunk 0.001  ladder 524288  sec_id 1 }
 *
 * Prices reach OB in ticks (Mbp2Mbo sends price / tick), so the asset's units
 * are 1 and a price on OB's ladder is a tick count. OB's ladder is a ring of
 * `ladder` slots per side (OB.hpp ring_mask); maxpx is only an upper bound for
 * a valid price, set far above any real one.
 */
void BnSimKaspr::load_config()
{
  boost::property_tree::ptree pt;
  boost::property_tree::read_info(opt_.config_dir + "/binance.ini", pt);
  auto s = pt.get_child_optional(opt_.symbol);
  ASSERTF(s, boost::format("no section %s in %s/binance.ini") % opt_.symbol % opt_.config_dir);

  feed_cfg_ = BinanceFeed::config_from_ini(*s, opt_.symbol, opt_.futures, char(venue_.value));
  ladder_ = s->get<int>("ladder", 1 << 19);

  // RefData must exist before assets are added; seed it empty, as SimKaspr does.
  {
    const std::string seed = "bnsim_universe_seed.csv";
    std::ofstream f(seed);
    f << "# generated by bnsim\n";
    f.close();
    frame::ref::RefData::set_universe(seed);
    frame::ref::RefData::inst();
  }
  const std::string name = opt_.symbol + (opt_.futures ? "_F" : "");
  auto a = frame::ref::RefData::add_future_asset(name, venue_, feed_cfg_.chunks.sec_id,
                                                 "", opt_.symbol, 1.0);
  ASSERT(a, "add_future_asset failed");
  a->maxpx = 1 << 30;
  asset_id_ = a->id;

  std::cerr << "bnsim: " << name << " on " << en::to_string(venue_) << " tick "
            << feed_cfg_.chunks.tick << " chunk " << feed_cfg_.chunks.chunk << " ladder "
            << ladder_ << std::endl;
}

void BnSimKaspr::create_order_book()
{
  order_books_.resize(en::x_num_syms());
  for (auto &row : order_books_)
    row.resize(asset_id_ + 1, nullptr);

  boost::property_tree::ptree pt_model;
  pt_model.put("ladder_ticks", ladder_);
  auto ob = new frame::ob::act::OB(nullptr, true /*cross_check*/, this, asset_id_, pt_model);
  group_->add(ob);
  if (opt_.ob_delay_us >= 0)
    ob_set_delay(ob, opt_.ob_delay_us);
  ob_set_feed_delay(ob, opt_.ob_feed_delay_us);
  order_books_[venue_][asset_id_] = ob;
  ob_ = ob;
}

// Crypto trades around the clock, so the probe gets one session from now for
// probe_days days, and windows of at least probe_window_min minutes inside it.
void BnSimKaspr::create_probe()
{
  if (opt_.probe_size <= 0)
    return;
  const uint64_t now = uint64_t(std::chrono::duration_cast<std::chrono::nanoseconds>(
                                    std::chrono::system_clock::now().time_since_epoch())
                                    .count());
  SlippageProbe::Config cfg;
  cfg.sym_name = frame::ref::RefData::inst().get_asset(asset_id_)->name;
  cfg.sym = asset_id_;
  cfg.parent_sz = opt_.probe_size;
  cfg.sessions.emplace_back(now, now + uint64_t(opt_.probe_days) * 86400ull * 1000000000ull);
  cfg.session_start = cfg.sessions.front().first;
  cfg.session_end = cfg.sessions.front().second;
  cfg.tick_s = 1;
  cfg.min_window_ns = uint64_t(opt_.probe_window_min) * 60ull * 1000000000ull;
  cfg.out_path = opt_.probe_out;
  probe_ = new SlippageProbe(ob_, timer_, cfg);
  group_->add(probe_);
}

void BnSimKaspr::create_som()
{
  boost::property_tree::ptree pt_som;
  boost::property_tree::read_info(opt_.config_dir + "/som.ini", pt_som);
  som_ = create_SOM(venue_, nullptr, pt_som, order_books_, true /*sim_mode*/, false, false, probe_);
  group_->add(som_);
}

// As SimKaspr::create_lights: one PCoord and one QCoord per side, N passive
// lights per side, each with its own mmid and name (the name seeds its RNG).
void BnSimKaspr::create_lights()
{
  boost::property_tree::ptree pt_light;
  boost::property_tree::read_info(opt_.config_dir + "/lights.ini", pt_light);
  if (opt_.rng_seed)
    pt_light.put("rng_seed", opt_.rng_seed);
  pt_light.put("aggr_participation_bp", 0);
  const int n = pt_light.get<int>("nlights_per_side", 4);
  const auto name = frame::ref::RefData::inst().get_asset(asset_id_)->name;

  pcoord_buy_ = create_PCoord();
  pcoord_sel_ = create_PCoord();
  pcoord_map_[name + "_BUY"] = pcoord_buy_;
  pcoord_map_[name + "_SEL"] = pcoord_sel_;
  auto qcoord_buy = create_QCoord();
  auto qcoord_sel = create_QCoord();

  for (int i = 0; i < n; i++)
  {
    auto b = create_light22_Shadow_BUY("bnsim", nullptr, nullptr,
                                       "L_" + name + "_BUY_" + std::to_string(i),
                                       en::trader::SIMULATOR, name, venue_, venue_, qcoord_buy,
                                       pcoord_buy_, ob_, nullptr, 0, timer_, som_, i, pt_light, 0,
                                       false);
    group_->add(b);
    buy_lights_.push_back(b);
    auto s = create_light22_Shadow_SEL("bnsim", nullptr, nullptr,
                                       "L_" + name + "_SEL_" + std::to_string(i),
                                       en::trader::SIMULATOR, name, venue_, venue_, qcoord_sel,
                                       pcoord_sel_, ob_, nullptr, 0, timer_, som_, i, pt_light, 0,
                                       false);
    group_->add(s);
    sel_lights_.push_back(s);
  }
  std::cerr << "bnsim: " << 2 * n << " lights on " << name << std::endl;
}

void BnSimKaspr::create_feed()
{
  feed_ = new BinanceFeed(feed_cfg_, ob_);
  add_to_manage_q(feed_);
}


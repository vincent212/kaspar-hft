  using namespace std::chrono_literals;

  template <class P>
  bool wait_until(P p, std::chrono::milliseconds limit = std::chrono::seconds(5))
  {
    auto end = std::chrono::steady_clock::now() + limit;
    while (std::chrono::steady_clock::now() < end)
    {
      if (p())
        return true;
      std::this_thread::sleep_for(2ms);
    }
    return p();
  }

  class Recorder : public actors::Actor
  {
  public:
    explicit Recorder(const char *n) { strncpy(name, n, sizeof(name) - 1); }
    ~Recorder() override
    {
      for (auto m : msgs)
        delete m;
    }
    const char *get_name() const override { return name; }
    void send(const actors::Message *m, actors::Actor *) noexcept override
    {
      std::lock_guard<std::mutex> l(mu);
      msgs.push_back(m);
    }
    template <class T>
    std::vector<const T *> all()
    {
      std::lock_guard<std::mutex> l(mu);
      std::vector<const T *> v;
      for (auto m : msgs)
        if (auto t = dynamic_cast<const T *>(m))
          v.push_back(t);
      return v;
    }
    template <class T>
    const T *wait_for(size_t nth = 0, std::chrono::milliseconds limit = std::chrono::seconds(5))
    {
      const T *r = nullptr;
      wait_until(
          [&] {
            auto v = all<T>();
            if (v.size() > nth)
            {
              r = v[nth];
              return true;
            }
            return false;
          },
          limit);
      return r;
    }
    std::vector<std::string> replies()
    {
      namespace som = frame::som::msg;
      std::lock_guard<std::mutex> l(mu);
      std::vector<std::string> v;
      for (auto m : msgs)
      {
        if (dynamic_cast<const som::Ack *>(m))
          v.push_back("Ack");
        else if (dynamic_cast<const som::Fill *>(m))
          v.push_back("Fill");
        else if (dynamic_cast<const som::CancAck *>(m))
          v.push_back("CancAck");
        else if (dynamic_cast<const som::CancReject *>(m))
          v.push_back("CancReject");
        else if (dynamic_cast<const som::Reject *>(m))
          v.push_back("Reject");
      }
      return v;
    }

  private:
    std::mutex mu;
    std::vector<const actors::Message *> msgs;
  };

  struct Assets
  {
    int btc = -1, eth = -1;
  };

  // RefData assets for the two instruments, created once per process.
  inline Assets assets()
  {
    static Assets a;
    static std::once_flag once;
    std::call_once(once, [] {
      const std::string seed = "build/deribit_oe_test_universe_seed.csv";
      std::ofstream(seed) << "# generated by the Deribit order-entry tests\n";
      frame::ref::RefData::set_universe(seed, "");
      frame::ref::RefData::inst();
      a.btc = int(frame::ref::RefData::add_future_asset("BTC-PERPETUAL_DBT", en::x::DERIBIT, 890001, "",
                                                        "BTC-PERPETUAL", 1.0)->id);
      a.eth = int(frame::ref::RefData::add_future_asset("ETH_USDC-PERPETUAL_DBT", en::x::DERIBIT, 890002, "",
                                                        "ETH_USDC-PERPETUAL", 1.0)->id);
    });
    return a;
  }

  // Test-environment configuration with both instruments; sym resolved.
  inline DeribitOMConfig test_config()
  {
    auto a = assets();
    DeribitOMConfig c;
    c.ep.test = true;
    c.ep.host = kTestHost;
    c.key_file = "/nonexistent/deribit_test.json";   // never read: the fake has no network
    c.reconnect_ms = 50;
    c.max_orders_per_sec = 0;
    Instrument b;
    b.asset = "BTC-PERPETUAL_DBT";
    b.name = "BTC-PERPETUAL";
    b.currency = "BTC";
    b.tick = "0.5";
    b.qty_unit = "10";   // USD: one contract
    b.inverse = true;
    b.sym = a.btc;
    Instrument e;
    e.asset = "ETH_USDC-PERPETUAL_DBT";
    e.name = "ETH_USDC-PERPETUAL";
    e.currency = "USDC";
    e.tick = "0.1";
    e.qty_unit = "0.001";   // ETH
    e.inverse = false;
    e.sym = a.eth;
    c.instruments = {b, e};
    return c;
  }

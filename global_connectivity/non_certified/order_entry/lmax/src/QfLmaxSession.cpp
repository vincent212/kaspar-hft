// QfLmaxSession: LmaxSession over a QuickFIX initiator.

#include <atomic>

#include "quickfix/Application.h"
#include "quickfix/Session.h"

#include "lmax_fix/FixInitiator.hpp"
#include "lmax_om/LmaxSession.hpp"

namespace lmax::om
{
  namespace
  {
    class QfLmaxSession : public LmaxSession, public FIX::Application
    {
    public:
      QfLmaxSession(const QfSessionConfig &cfg, SessionEvents &ev) : cfg_(cfg), ev_(ev)
      {
        fix_ = std::make_unique<fix::FixInitiator>(cfg_.params, *this);
      }
      ~QfLmaxSession() override { stop(); }

      void start() override { fix_->start(); }
      void stop() override
      {
        if (fix_)
          fix_->stop();
      }

      CallStatus send_new(const NewOrderReq &r) override { return send(build_new_order(r)); }
      CallStatus send_cancel(const CancelReq &r) override { return send(build_cancel(r)); }
      CallStatus send_replace(const ReplaceReq &r) override { return send(build_replace(r)); }
      CallStatus send_status(const StatusReq &r) override { return send(build_status(r)); }
      CallStatus send_tcr_request(const TcrReq &r) override { return send(build_tcr_request(r)); }

      // FIX::Application, on QuickFIX's thread.
      void onCreate(const FIX::SessionID &) override {}
      void onLogon(const FIX::SessionID &) override
      {
        logged_on_ = true;
        ev_.logged_on();
      }
      void onLogout(const FIX::SessionID &) override
      {
        logged_on_ = false;
        ev_.logged_out(last_logout_text_);
        last_logout_text_.clear();
      }
      void toAdmin(FIX::Message &m, const FIX::SessionID &) override
      {
        if (m.getHeader().getField(35) == "A")
        {
          m.setField(553, cfg_.username);
          m.setField(554, cfg_.password);
        }
      }
      void toApp(FIX::Message &m, const FIX::SessionID &) override
      {
        // Only the requests this class builds are sent; a Reject or
        // BusinessMessageReject generated by QuickFIX is not an app message
        // in LMAX's dictionary and never reaches here.
      }
      void fromAdmin(const FIX::Message &m, const FIX::SessionID &) override
      {
        try
        {
          const std::string &t = m.getHeader().getField(35);
          if (t == "3")
            ev_.session_reject((m.isSetField(373) ? "reason " + m.getField(373) + ": " : std::string()) +
                               (m.isSetField(58) ? m.getField(58) : std::string()));
          else if (t == "5")
            last_logout_text_ = m.isSetField(58) ? m.getField(58) : std::string();
        }
        catch (...)
        {
        }
      }
      // Never throws (an exception would make QuickFIX reject the report).
      void fromApp(const FIX::Message &m, const FIX::SessionID &) override
      {
        std::string err;
        try
        {
          const std::string &t = m.getHeader().getField(35);
          if (t == "8")
          {
            ExecReport r;
            if (!parse_exec(m, r, err))
              return ev_.unparsed(err + ": " + m.toString());
            r.raw = m.toString();
            ev_.exec(r);
          }
          else if (t == "9")
          {
            CancelReject r;
            if (!parse_cancel_reject(m, r, err))
              return ev_.unparsed(err + ": " + m.toString());
            ev_.cancel_reject(r);
          }
          else if (t == "AE")
          {
            TradeCaptureReport r;
            if (!parse_tcr(m, r, err))
              return ev_.unparsed(err + ": " + m.toString());
            r.raw = m.toString();
            ev_.trade_capture(r);
          }
          else if (t == "AQ")
          {
            TcrAck a;
            if (!parse_tcr_ack(m, a, err))
              return ev_.unparsed(err + ": " + m.toString());
            ev_.tcr_ack(a);
          }
          else
            ev_.unparsed("unexpected MsgType " + t);
        }
        catch (const std::exception &e)
        {
          ev_.unparsed(e.what());
        }
      }

    private:
      CallStatus send(FIX::Message m)
      {
        if (!logged_on_)
          return CallStatus::Disconnected;
        return fix_->send(std::move(m)) ? CallStatus::Success : CallStatus::Disconnected;
      }

      QfSessionConfig cfg_;
      SessionEvents &ev_;
      std::unique_ptr<fix::FixInitiator> fix_;
      std::atomic<bool> logged_on_{false};
      std::string last_logout_text_;
    };
  }

  SessionFactory qf_session_factory(QfSessionConfig cfg)
  {
    return [cfg](SessionEvents &ev) -> std::unique_ptr<LmaxSession> {
      return std::make_unique<QfLmaxSession>(cfg, ev);
    };
  }
}

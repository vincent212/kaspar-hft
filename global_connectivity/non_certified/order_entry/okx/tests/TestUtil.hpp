  using namespace std::chrono_literals;

  template <class P>
  bool wait_until(P p, std::chrono::milliseconds limit = std::chrono::seconds(5))
  {
    auto end = std::chrono::steady_clock::now() + limit;
    while (std::chrono::steady_clock::now() < end)
    {
      if (p())
        return true;
      std::this_thread::sleep_for(2ms);
    }
    return p();
  }

  class Recorder : public actors::Actor
  {
  public:
    explicit Recorder(const char *n) { strncpy(name, n, sizeof(name) - 1); }
    ~Recorder() override
    {
      for (auto m : msgs)
        delete m;
    }
    const char *get_name() const override { return name; }
    void send(const actors::Message *m, actors::Actor *) noexcept override
    {
      std::lock_guard<std::mutex> l(mu);
      msgs.push_back(m);
    }
    template <class T>
    std::vector<const T *> all()
    {
      std::lock_guard<std::mutex> l(mu);
      std::vector<const T *> v;
      for (auto m : msgs)
        if (auto t = dynamic_cast<const T *>(m))
          v.push_back(t);
      return v;
    }
    template <class T>
    const T *wait_for(size_t nth = 0, std::chrono::milliseconds limit = std::chrono::seconds(5))
    {
      const T *r = nullptr;
      wait_until(
          [&] {
            auto v = all<T>();
            if (v.size() > nth)
            {
              r = v[nth];
              return true;
            }
            return false;
          },
          limit);
      return r;
    }
    std::vector<std::string> replies()
    {
      namespace som = frame::som::msg;
      std::lock_guard<std::mutex> l(mu);
      std::vector<std::string> v;
      for (auto m : msgs)
      {
        if (dynamic_cast<const som::Ack *>(m))
          v.push_back("Ack");
        else if (dynamic_cast<const som::Fill *>(m))
          v.push_back("Fill");
        else if (dynamic_cast<const som::CancAck *>(m))
          v.push_back("CancAck");
        else if (dynamic_cast<const som::CancReject *>(m))
          v.push_back("CancReject");
        else if (dynamic_cast<const som::Reject *>(m))
          v.push_back("Reject");
      }
      return v;
    }

  private:
    std::mutex mu;
    std::vector<const actors::Message *> msgs;
  };

  struct Assets
  {
    int spot = -1, swap = -1;
  };

  // RefData assets for the two instruments, created once per process.
  inline Assets assets()
  {
    static Assets a;
    static std::once_flag once;
    std::call_once(once, [] {
      const std::string seed = "build/okx_oe_test_universe_seed.csv";
      std::ofstream(seed) << "# generated by the OKX order-entry tests\n";
      frame::ref::RefData::set_universe(seed, "");
      frame::ref::RefData::inst();
      a.spot = int(frame::ref::RefData::add_future_asset("BTC-USDT_OKXT", en::x::OKX, 880001, "", "BTC-USDT", 1.0)->id);
      a.swap = int(
          frame::ref::RefData::add_future_asset("BTC-USDT-SWAP_OKXT", en::x::OKXF, 880002, "", "BTC-USDT-SWAP", 1.0)->id);
    });
    return a;
  }

  // Demo configuration with both instruments; sym resolved.
  inline OkxOMConfig demo_config()
  {
    auto a = assets();
    OkxOMConfig c;
    c.ep.demo = true;
    c.ep.ws_host = "wspap.okx.com";
    c.key_file = "/nonexistent/okx_demo.json"; // never read: the fake has no network
    c.reconnect_ms = 50;
    c.max_orders_per_sec = 0;
    Instrument s;
    s.asset = "BTC-USDT_OKXT";
    s.inst_id = "BTC-USDT";
    s.inst_id_code = 3;
    s.inst_type = "SPOT";
    s.td_mode = "cash";
    s.tick = "0.1";
    s.qty_unit = "0.0001";
    s.venue = en::x::OKX;
    s.sym = a.spot;
    Instrument w;
    w.asset = "BTC-USDT-SWAP_OKXT";
    w.inst_id = "BTC-USDT-SWAP";
    w.inst_id_code = 10459;
    w.inst_type = "SWAP";
    w.td_mode = "cross";
    w.tick = "0.1";
    w.qty_unit = "0.01";
    w.venue = en::x::OKXF;
    w.sym = a.swap;
    c.instruments = {s, w};
    return c;
  }

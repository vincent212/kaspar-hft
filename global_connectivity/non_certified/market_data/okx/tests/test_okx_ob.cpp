// The full chain on recorded OKX frames: OkxSync -> Mbp2Mbo -> a real OB.
// After every book message, OB's size at each of the best window levels must
// be the sync class's size in chunks, and OB's best bid and ask its best.

#include <gtest/gtest.h>

#include <boost/property_tree/ptree.hpp>
#include <cstdio>
#include <fstream>
#include <memory>
#include <string>

#include <nlohmann/json.hpp>

#include "bfile/r_l3.hpp"
#include "enum/e_names.hpp"
#include "frame/cons/msg/Get.hpp"
#include "frame/cons/msg/Page.hpp"
#include "frame/mda/msg/Data.hpp"
#include "frame/ob/act/OB.hpp"
#include "frame/ref/RefData.hpp"
#include "okx_md/OkxSync.hpp"
#include "unit_test/MockActor.hpp"
#include "unit_test/TestHelper.hpp"

using okx::md::OkxSync;

namespace
{
  struct TestableOB : public frame::ob::act::OB
  {
    using frame::ob::act::OB::OB;
    using frame::ob::act::OB::reply_to;
  };

  class OkxOBTest : public ::testing::Test
  {
  protected:
    unit_test::MockActor probe{"probe"};
    std::unique_ptr<TestableOB> ob;
    std::unique_ptr<sim::Mbp2Mbo> m;
    std::unique_ptr<OkxSync> s;
    static constexpr size_t kWindow = 20;
    static int next_sec_;

    static void SetUpTestSuite()
    {
      const std::string seed = "build/okx_test_universe_seed.csv";
      std::ofstream(seed) << "# generated by run_okx_md_tests\n";
      frame::ref::RefData::set_universe(seed, "");
      frame::ref::RefData::inst();
    }

    void make(const char *inst, en::x venue, double chunk)
    {
      const int sec = ++next_sec_;
      auto a = frame::ref::RefData::add_future_asset(std::string(inst) + "_T" + std::to_string(sec), venue, sec, "",
                                                     inst, 1.0);
      ASSERT_NE(a, nullptr);
      a->maxpx = 1 << 30;
      boost::property_tree::ptree pt;
      pt.put("ladder_ticks", 524288);
      ob = std::make_unique<TestableOB>(nullptr, true, nullptr, a->id, pt);
      m = std::make_unique<sim::Mbp2Mbo>(sim::Mbp2Mbo::Config{sec, char(venue), 0.1, chunk},
                                         [this](const bfile::l3_t &r) {
                                           frame::mda::msg::Data d(true);
                                           d.l3 = r;
                                           dispatch(&d);
                                         });
      s = std::make_unique<OkxSync>(inst, *m, kWindow);
    }

    void dispatch(const actors::Message *msg)
    {
      ob->reply_to = &probe;
      unit_test::TestHelper::invoke_handler(ob.get(), msg, &probe);
      ob->reply_to = nullptr;
    }

    int qat(bool bid, int64_t t)
    {
      probe.clear();
      frame::cons::msg::Get g("qat", {{"side", bid ? "B" : "S"}, {"px", std::to_string(t)}});
      dispatch(&g);
      auto page = probe.get_message<frame::cons::msg::Page>(0);
      int sz = -1, cnt = -1, sim = -1;
      if (page)
        std::sscanf(page->val.c_str(), "QAT: %d %d %d", &sz, &cnt, &sim);
      return sz;
    }

    std::pair<int, int> bbo()
    {
      probe.clear();
      frame::cons::msg::Get g("bbbo");
      dispatch(&g);
      auto page = probe.get_message<frame::cons::msg::Page>(0);
      int b = -1, a = -1;
      if (page)
        std::sscanf(page->val.c_str(), "BBBO: %d %d", &b, &a);
      return {b, a};
    }

    void run(const char *inst)
    {
      size_t checks = 0, levels = 0;
      s->on_book = [&](int64_t) {
        ++checks;
        size_t n = 0;
        for (auto it = s->bids().rbegin(); it != s->bids().rend() && n < kWindow; ++it, ++n, ++levels)
          ASSERT_EQ(qat(true, it->first), int(m->target(it->second.qty))) << "bid " << it->first;
        n = 0;
        for (auto it = s->asks().begin(); it != s->asks().end() && n < kWindow; ++it, ++n, ++levels)
          ASSERT_EQ(qat(false, it->first), int(m->target(it->second.qty))) << "ask " << it->first;
        auto [b, a] = bbo();
        ASSERT_EQ(b, int(s->bids().rbegin()->first));
        ASSERT_EQ(a, int(s->asks().begin()->first));
      };
      std::ifstream f("tests/data/okx_btc_spot_swap_20261118.rec");
      ASSERT_TRUE(f.good());
      std::string l;
      while (std::getline(f, l))
      {
        if (l.size() < 3 || l[0] != 'W')
          continue;
        const auto body = l.substr(l.find(' ', 2) + 1);
        if (body == "pong")
          continue;
        ASSERT_NE(s->on_message(nlohmann::json::parse(body)), OkxSync::Status::Gap);
      }
      EXPECT_GT(checks, 50u);
      EXPECT_EQ(levels, checks * 2 * kWindow);
      EXPECT_GT(s->stats().trades, 0u);
    }
  };
  int OkxOBTest::next_sec_ = 100;
}

TEST_F(OkxOBTest, SpotChainKeepsOBInStepWithTheBook)
{
  make("BTC-USDT", en::x::OKX, 0.01);
  run("BTC-USDT");
}

TEST_F(OkxOBTest, SwapChainKeepsOBInStepWithTheBook)
{
  make("BTC-USDT-SWAP", en::x::OKXF, 1.0);
  run("BTC-USDT-SWAP");
}

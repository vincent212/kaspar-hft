#pragma once

// LMAX trade reports into post_trade::msg::TradeCapture. NOT CERTIFIED.
//
// Two sources describe the same trades (feed.md section 6):
//   - TradeCaptureReport (35=AE), the answer to a TradeCaptureReportRequest
//     on a Broker Trading session (historic trades and, with
//     SubscriptionRequestType 1, new ones);
//   - ExecutionReport (35=8) with ExecType F (trade), G (trade correct) or
//     H (trade cancel), on the session that placed the order.
//
// Identifiers (review.md, decision 1). LMAX gives each fill an ExecID "unique
// over all time" and a SecondaryExecID, "the execution ID as generated by the
// MTF", set only on trades. Whether an AE's ExecID equals the ExecID of the
// ExecutionReport for the same fill is not stated. Reading taken: the trade
// is identified by (OrderID, SecondaryExecID), both of which appear in both
// messages; ExecID is used in their place only when SecondaryExecID is absent
// or "0". The New report's report_id is derived from that trade id, so the
// same fill from both sources is one report to the ledger (Duplicate).
//
// Corrections and cancels (ExecType G, H) carry no reference to the trade
// they change: LMAX's dictionary has no ExecRefID (review.md, decision 2). Reading taken: they carry
// the corrected trade's SecondaryExecID; a G or H without one cannot be
// linked and is returned as not mapped.
//
// Quantities are in Kaspar units (LastQty / the instrument's contracts per
// unit, as the order manager counts them); prices are kept as LMAX's decimal
// text (mantissa and decimals). trade_time_ns is nanoseconds since UTC
// midnight of the TransactTime (LMAX gives UTC timestamps; review.md, low
// impact).

#include <map>
#include <string>

#include "enum/exch_code.hpp"
#include "lmax_om/ExecParse.hpp"
#include "post_trade/msg/TradeCapture.hpp"

namespace lmax::pt
{
  struct PtInstrument
  {
    int asset = -1;
    double unit = 0.1; // contracts per Kaspar unit
  };

  struct MapContext
  {
    en::x venue;
    std::map<std::string, PtInstrument> instruments; // LMAX SecurityID -> Kaspar
  };

  // "1.15229" -> 115229, 5. false if not a plain decimal.
  bool decimal_text(const std::string &s, int64_t &mantissa, int &decimals);

  // A TradeCaptureReport. false (reason in err) if it cannot be mapped.
  bool from_tcr(const om::TradeCaptureReport &r, const MapContext &ctx, post_trade::msg::TradeCapture &out,
                std::string &err);

  // An ExecutionReport with ExecType F, G or H.
  bool from_exec(const om::ExecReport &r, const MapContext &ctx, post_trade::msg::TradeCapture &out, std::string &err);

  // The trade id rule above.
  std::string trade_id(const std::string &order_id, const std::string &secondary, const std::string &exec_id);

  // The start of the LMAX trading day that contains utc_ns: 17:00 New York
  // time (Broker Trading spec, session schedule; LMAX's operating day), as ns
  // since the epoch, with US daylight saving applied.
  uint64_t trading_day_start_ns(uint64_t utc_ns);
  // UTCTimestamp text for ns since the epoch, milliseconds.
  std::string utc_timestamp(uint64_t ns);
}
